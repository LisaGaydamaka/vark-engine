std::vector<uint8_t> BitmapFont::generate_font_texture()
{
    std::vector<uint8_t> pixels(TEXTURE_WIDTH * TEXTURE_HEIGHT * 4, 0);

    for (int char_idx = 0; char_idx < 95; char_idx++) {
        int grid_x = char_idx % GLYPHS_PER_ROW;
        int grid_y = char_idx / GLYPHS_PER_ROW;

        int start_x = grid_x * GLYPH_WIDTH;
        int start_y = grid_y * GLYPH_HEIGHT;

        const uint8_t* glyph = font_data[char_idx];

        for (int row = 0; row < 8; row++) {
            for (int col = 0; col < 8; col++) {
                uint8_t bit = (glyph[row] >> (7 - col)) & 1;
                int px = start_x + col;
                int py = start_y + row;
                int idx = (py * TEXTURE_WIDTH + px) * 4;
                uint8_t val = bit ? 255 : 0;
                pixels[idx + 0] = 255;
                pixels[idx + 1] = 255;
                pixels[idx + 2] = 255;
                pixels[idx + 3] = val;
            }
        }
    }

    return pixels;
}

void BitmapFont::get_char_uv(char c, float& u1, float& v1, float& u2, float& v2)
{
    int idx = (unsigned char)c - 32;
    if (idx < 0 || idx >= 95) idx = 0;

    int grid_x = idx % GLYPHS_PER_ROW;
    int grid_y = idx / GLYPHS_PER_ROW;

    float tx = (float)grid_x / GLYPHS_PER_ROW;
    float ty = (float)grid_y / GLYPH_ROWS;
    float tw = 1.0f / GLYPHS_PER_ROW;
    float th = 1.0f / GLYPH_ROWS;

    u1 = tx;
    v1 = ty;
    u2 = tx + tw;
    v2 = ty + th;
}

bool BitmapFont::create_texture(ID3D11Device* device, ID3D11ShaderResourceView** outView)
{
    std::vector<uint8_t> pixels = generate_font_texture();

    D3D11_TEXTURE2D_DESC texDesc = {};
    texDesc.Width = TEXTURE_WIDTH;
    texDesc.Height = TEXTURE_HEIGHT;
    texDesc.MipLevels = 1;
    texDesc.ArraySize = 1;
    texDesc.Format = DXGI_FORMAT_R8G8B8A8_UNORM;
    texDesc.SampleDesc.Count = 1;
    texDesc.Usage = D3D11_USAGE_DEFAULT;
    texDesc.BindFlags = D3D11_BIND_SHADER_RESOURCE;

    D3D11_SUBRESOURCE_DATA initData = {};
    initData.pSysMem = pixels.data();
    initData.SysMemPitch = TEXTURE_WIDTH * 4;

    ID3D11Texture2D* texture = nullptr;
    if (FAILED(device->CreateTexture2D(&texDesc, &initData, &texture))) {
        return false;
    }

    if (FAILED(device->CreateShaderResourceView(texture, nullptr, outView))) {
        texture->Release();
        return false;
    }

    texture->Release();
    return true;
}